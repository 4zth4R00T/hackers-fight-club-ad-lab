function plural(n: number, una: string, pocas: string, muchas: string): string {
  const centena = Math.abs(n) % 100;
  const unidad = centena % 10;
  if (centena >= 11 && centena <= 14) return muchas;
  if (unidad === 1) return una;
  if (unidad >= 2 && unidad <= 4) return pocas;
  return muchas;
}

